// tools/adr-index.js — generates docs/adr/ADR_INDEX.md from the front matter of every record in
// docs/adr/, newest first. Dependency-free Node (18 or later). The rules the records follow are in
// docs/adr/ADR_README.md; this tool enforces the machine-readable part of them and fails closed.
//
//   node tools/adr-index.js              write the index (also run by the Claude Code hook after any
//                                        write under docs/adr/)
//   node tools/adr-index.js --check      exit 1 if the index on disk differs from what the records say
//   node tools/adr-index.js --self-test  run the in-memory fixtures
//   node tools/adr-index.js --hook       Claude Code PostToolUse mode: reads the tool's JSON from stdin and
//                                        regenerates the index only when the written file is under docs/adr/
//
// Exit codes: 0 green · 1 stale index (--check only) · 2 a malformed record or an internal error.
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const ADR_DIR = path.join(ROOT, "docs", "adr");
const INDEX = path.join(ADR_DIR, "ADR_INDEX.md");

// adr-[M[C|R]]YYYYMMDDHHMM-slug.md : the slug is lowercase, hyphenated, at most 50 characters; the whole
// filename at most 80 (ADR_README, file names).
const NAME = /^adr-(M[CR]?)?(\d{12})-([a-z0-9]+(?:-[a-z0-9]+)*)\.md$/;
const FRONT = /^---\r?\n((?:[a-z]+:[^\r\n]*\r?\n)+)---\r?\n/;
const TIERS = ["mandate", "decision"];
const STATUSES = ["proposed", "accepted", "superseded"];

function parseRecord(name, text) {
  const m = NAME.exec(name);
  if (!m) return { error: "filename does not match adr-[M[C|R]]YYYYMMDDHHMM-slug.md" };
  if (name.length > 80) return { error: "filename longer than 80 characters" };
  if (m[3].length > 50) return { error: "slug longer than 50 characters" };
  const f = FRONT.exec(text);
  if (!f) return { error: "missing or malformed front matter (--- tier/status/made/supersedes ---)" };
  const fields = {};
  for (const line of f[1].split(/\r?\n/)) {
    if (!line) continue;
    const i = line.indexOf(":");
    fields[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  for (const k of ["tier", "status", "made", "supersedes"]) if (!(k in fields)) return { error: "front matter lacks '" + k + "'" };
  if (!TIERS.includes(fields.tier)) return { error: "tier must be one of " + TIERS.join(" | ") };
  if (!STATUSES.includes(fields.status)) return { error: "status must be one of " + STATUSES.join(" | ") };
  if (!/^\d{12}$/.test(fields.made)) return { error: "made must be YYYYMMDDHHMM" };
  if (fields.made !== m[2]) return { error: "made (" + fields.made + ") differs from the filename timestamp (" + m[2] + ")" };
  if (fields.tier === "mandate" && !m[1]) return { error: "a mandate's filename must carry M" };
  if (fields.tier === "decision" && m[1]) return { error: "a decision's filename must not carry M" };
  if (!(fields.supersedes === "none" || /^adr-(M[CR]?)?\d{12}$/.test(fields.supersedes))) return { error: "supersedes must be 'none' or an adr-… id" };
  const rest = text.slice(f[0].length);
  const h = /^#\s+(.+?)\s*$/m.exec(rest);
  if (!h) return { error: "no '# headline' after the front matter" };
  const promoted = m[1] === "MC" ? "CLAUDE.md" : m[1] === "MR" ? "README.md" : "";
  return { id: "adr-" + (m[1] || "") + m[2], file: name, made: m[2], tier: fields.tier, status: fields.status, supersedes: fields.supersedes, headline: h[1], promoted };
}

function render(records) {
  const rows = records.slice().sort((a, b) => (a.made < b.made ? 1 : a.made > b.made ? -1 : a.file < b.file ? -1 : 1));
  const lines = [
    "# ADR index",
    "",
    "Generated by `node tools/adr-index.js` from the front matter of every record in this folder. Do not edit;",
    "newest first. The rules are in [ADR_README.md](ADR_README.md).",
    "",
    "| Made | Record | Tier | Status | Headline | Supersedes |",
    "|---|---|---|---|---|---|"
  ];
  for (const r of rows) {
    const tier = r.tier + (r.promoted ? " (" + r.promoted + ")" : "");
    lines.push("| " + r.made + " | [" + r.id + "](" + r.file + ") | " + tier + " | " + r.status + " | " + r.headline.replace(/\|/g, "\\|") + " | " + r.supersedes + " |");
  }
  if (!rows.length) lines.push("| | | | | *(no records yet)* | |");
  return lines.join("\n") + "\n";
}

function scan(dir) {
  const records = [], errors = [];
  for (const name of fs.readdirSync(dir).sort()) {
    if (!name.startsWith("adr-") || !name.endsWith(".md")) continue;
    const r = parseRecord(name, fs.readFileSync(path.join(dir, name), "utf8"));
    if (r.error) errors.push(name + ": " + r.error); else records.push(r);
  }
  return { records, errors };
}

function selfTest() {
  const good = "---\ntier: decision\nstatus: accepted\nmade: 202610151430\nsupersedes: none\n---\n# Presets live in one JSON file\n\nbody\n";
  const fails = [];
  const ok = parseRecord("adr-202610151430-presets-single-source.md", good);
  if (ok.error || ok.headline !== "Presets live in one JSON file" || ok.id !== "adr-202610151430") fails.push("good record rejected: " + JSON.stringify(ok));
  const mandate = parseRecord("adr-MC202610151500-sole-operator.md", good.replace("decision", "mandate").replace("202610151430", "202610151500"));
  if (mandate.error || mandate.promoted !== "CLAUDE.md") fails.push("promoted mandate rejected: " + JSON.stringify(mandate));
  const bad = [
    ["adr-202610151430-Presets.md", good, "filename"],
    ["adr-202610151430-presets.md", good.replace("made: 202610151430", "made: 202610151431"), "differs from the filename"],
    ["adr-202610151430-presets.md", good.replace("decision", "mandate"), "must carry M"],
    ["adr-M202610151430-presets.md", good, "must not carry M"],
    ["adr-202610151430-presets.md", good.replace("accepted", "done"), "status must be"],
    ["adr-202610151430-presets.md", good.replace(/^# .*\n/m, ""), "no '# headline'"],
    ["adr-202610151430-presets.md", "no front matter\n", "front matter"]
  ];
  for (const [name, text, needle] of bad) {
    const r = parseRecord(name, text);
    if (!r.error || !r.error.includes(needle)) fails.push("expected '" + needle + "' for " + name + ", got " + JSON.stringify(r));
  }
  const out = render([ok, mandate]);
  if (out.indexOf("adr-MC202610151500") > out.indexOf("adr-202610151430")) fails.push("index is not newest first");
  if (!render([]).includes("no records yet")) fails.push("empty index lacks its placeholder row");
  for (const f of fails) console.error("SELF-TEST FAIL: " + f);
  if (!fails.length) console.log("adr-index self-test: one good record and one promoted mandate accepted; seven malformed records refused; order newest first");
  return fails.length ? 2 : 0;
}

function hookWants() {
  // The hook payload: { tool_name, tool_input: { file_path }, ... }. Anything unparseable means "not ours".
  let raw = "";
  try { raw = fs.readFileSync(0, "utf8"); } catch (e) { return false; }
  let p = "";
  try { const j = JSON.parse(raw); p = (j.tool_input && j.tool_input.file_path) || (j.tool_response && j.tool_response.filePath) || ""; } catch (e) { return false; }
  p = String(p).replace(/\\/g, "/");
  return /\/docs\/adr\/adr-[^/]+\.md$/.test(p);
}

function main(argv) {
  try {
    if (argv.includes("--self-test")) return selfTest();
    if (argv.includes("--hook") && !hookWants()) return 0;
    if (!fs.existsSync(ADR_DIR)) { console.error("adr-index: docs/adr/ does not exist"); return 2; }
    const { records, errors } = scan(ADR_DIR);
    for (const e of errors) console.error("MALFORMED: " + e);
    if (errors.length) { console.error("adr-index: " + errors.length + " malformed record(s) — nothing written"); return 2; }
    const wanted = render(records);
    if (argv.includes("--check")) {
      const have = fs.existsSync(INDEX) ? fs.readFileSync(INDEX, "utf8") : "";
      if (have.replace(/\r\n/g, "\n") !== wanted) { console.error("adr-index: ADR_INDEX.md is stale — run `node tools/adr-index.js`"); return 1; }
      console.log("adr-index: index current (" + records.length + " record(s))");
      return 0;
    }
    fs.writeFileSync(INDEX, wanted);
    console.log("adr-index: wrote docs/adr/ADR_INDEX.md (" + records.length + " record(s))");
    return 0;
  } catch (e) {
    console.error("adr-index INTERNAL ERROR (fail closed): " + (e && e.message));
    return 2;
  }
}

process.exit(main(process.argv.slice(2)));
